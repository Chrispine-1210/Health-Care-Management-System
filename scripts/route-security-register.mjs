import fs from 'node:fs';
import path from 'node:path';

const sources = ['server/auth-routes.ts', 'server/email-routes.ts', 'server/routes.ts'];
const outputPath = 'docs/route-security-register.md';

function contextFor(route) {
  const value = route.toLowerCase();
  const ownership = /patient|users\/:id|orders\/:id|payments/.test(value) ? 'Owner or scoped permission' : '-';
  const branch = /admin|staff|inventory|orders|branches|appointments/.test(value) ? 'Actor/resource branch where applicable' : '-';
  const assignment = /clinical|prescriptions/.test(value) ? 'Clinical assignment or approved workflow' : /deliver/.test(value) ? 'Assigned driver' : '-';
  const workflow = /review|approve|reject|status|payment|override/.test(value) ? 'Validated state transition' : '-';
  return { ownership, branch, assignment, workflow };
}

const rows = [];
for (const file of sources) {
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);
  lines.forEach((line, index) => {
    const match = line.match(/app\.(get|post|put|patch|delete)\(['"]([^'"]+)['"](.*)$/);
    if (!match) return;
    const [, method, route, tail] = match;
    const authenticated = tail.includes('authenticateToken');
    const permission = tail.match(/requirePermission\(PERMISSIONS\.([A-Z_]+)\)/)?.[1] ?? (authenticated ? 'CONTEXTUAL_POLICY' : 'PUBLIC');
    const context = contextFor(route);
    rows.push({ method: method.toUpperCase(), route, authenticated, permission, ...context, response: authenticated ? '401 / 403 or 404' : '-', coverage: 'Policy; handler coverage pending', source: `${file}:${index + 1}` });
  });
}

const header = `# Route Security Register\n\nGenerated by \`npm run route-security:generate\`. Do not edit manually.\n\nRoutes inventoried: ${rows.length}\n\n| Method | Route | Auth | Permission | Ownership | Branch | Assignment | Workflow state | Unauthorized | Coverage | Source |\n|---|---|---:|---|---|---|---|---|---|---|---|`;
const body = rows.map((row) => `| ${row.method} | \`${row.route}\` | ${row.authenticated ? 'Yes' : 'No'} | ${row.permission} | ${row.ownership} | ${row.branch} | ${row.assignment} | ${row.workflow} | ${row.response} | ${row.coverage} | \`${row.source}\` |`).join('\n');
const content = `${header}\n${body}\n`;

const legacy = sources.flatMap((file) => fs.readFileSync(file, 'utf8').match(/requireRole\(/g) ?? []);
if (legacy.length) throw new Error(`Legacy role gates remain: ${legacy.length}`);

if (process.argv.includes('--check')) {
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8').replace(/\r\n/g, '\n') !== content) {
    throw new Error('Route security register is stale. Run npm run route-security:generate.');
  }
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, content);
  process.stdout.write(`Wrote ${outputPath} with ${rows.length} routes.\n`);
}
